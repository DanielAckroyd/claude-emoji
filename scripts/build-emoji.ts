// Regenerates hooks/emoji.ts from iamcal/emoji-data (MIT), the set Slack's
// shortcodes come from:
//   curl -sSfLo /tmp/emoji.json https://cdn.jsdelivr.net/npm/emoji-datasource@16.0.0/emoji.json
//   bun scripts/build-emoji.ts /tmp/emoji.json 16.0.0
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

type Row = { short_names: string[]; unified: string; category: string; sort_order: number }

const [source, version = 'unknown'] = process.argv.slice(2)
if (!source) throw new Error('usage: bun scripts/build-emoji.ts <emoji.json> [version]')

const rows = (JSON.parse(readFileSync(source, 'utf8')) as Row[])
  // skin-tone modifiers aren't emoji on their own
  .filter(r => r.category !== 'Component')
  .sort((a, b) => a.sort_order - b.sort_order)

const char = (unified: string) => String.fromCodePoint(...unified.split('-').map(h => parseInt(h, 16)))

const lines = rows.map(r => {
  const [name, ...aliases] = r.short_names
  const extra = aliases.length ? `, aliases: ${JSON.stringify(aliases)}` : ''
  return `  { name: ${JSON.stringify(name)}, char: ${JSON.stringify(char(r.unified))}, category: ${JSON.stringify(r.category)}${extra} },`
})

const out = `// Generated by scripts/build-emoji.ts from emoji-datasource@${version}
// (iamcal/emoji-data, MIT): Slack's standard shortcodes. Don't edit by hand.
export type Emoji = { name: string; char: string; category?: string; aliases?: readonly string[] }

export const EMOJI: readonly Emoji[] = [
${lines.join('\n')}
]
`

writeFileSync(join(import.meta.dir, '..', 'hooks', 'emoji.ts'), out)
console.log(`wrote ${rows.length} emoji`)
