// Regenerates hooks/gemoji.ts from github/gemoji (MIT), the names GitHub uses:
//   curl -sSfLo /tmp/gemoji.json https://cdn.jsdelivr.net/gh/github/gemoji@v4.1.0/db/emoji.json
//   bun scripts/build-gemoji.ts /tmp/gemoji.json 4.1.0
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { EXTRA_ALIASES } from '../hooks/aliases'
import { EMOJI } from '../hooks/emoji'

type Row = { emoji: string; aliases: string[] }

const [source, version = 'unknown'] = process.argv.slice(2)
if (!source) throw new Error('usage: bun scripts/build-gemoji.ts <emoji.json> [version]')

// gemoji and Slack disagree on variation selectors
const bare = (char: string) => char.replaceAll('️', '')

const slackByChar = new Map(EMOJI.map(e => [bare(e.char), e.name]))
const taken = new Set([
  ...EMOJI.flatMap(e => [e.name, ...(e.aliases ?? [])]),
  ...Object.values(EXTRA_ALIASES).flat(),
])

// Slack's names and the hand-kept aliases win, so :umbrella: stays Slack's ☂️
const added = new Map<string, string[]>()
for (const r of JSON.parse(readFileSync(source, 'utf8')) as Row[]) {
  const name = slackByChar.get(bare(r.emoji))
  if (!name) continue
  const fresh = r.aliases.filter(a => !taken.has(a))
  if (fresh.length) added.set(name, [...(added.get(name) ?? []), ...fresh])
}

const lines = EMOJI.filter(e => added.has(e.name)).map(
  e => `  ${JSON.stringify(e.name)}: ${JSON.stringify(added.get(e.name))},`,
)

const out = `// Generated by scripts/build-gemoji.ts from github/gemoji@${version} (MIT): GitHub's
// names that Slack lacks, keyed by Slack's name. Don't edit by hand.
export const GEMOJI_ALIASES: Readonly<Record<string, readonly string[]>> = {
${lines.join('\n')}
}
`

writeFileSync(join(import.meta.dir, '..', 'hooks', 'gemoji.ts'), out)
console.log(`wrote ${[...added.values()].flat().length} names for ${added.size} emoji`)
